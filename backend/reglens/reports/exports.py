"""DRAFT CTR / STR / CBWTR exports — generated only from human-approved decisions."""

from __future__ import annotations

import csv
import io
from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session, selectinload

from reglens.core.models import Account, Decision, Transaction
from reglens.core.utils import format_inr, mask_account

REPORT_TYPES = {"CTR": "Cash Transaction Report", "STR": "Suspicious Transaction Report",
                "CBWTR": "Cross-Border Wire Transfer Report"}
COLUMNS = ["report_type", "decision_id", "transaction_id", "transaction_date", "account_masked", "amount_inr",
           "channel", "direction", "counterparty_country", "rules", "deadline", "approved_by", "approved_at"]


def report_rows(session: Session, report_type: str) -> list[dict[str, Any]]:
    report_type = report_type.upper()
    if report_type not in REPORT_TYPES:
        raise KeyError(report_type)
    decisions = session.scalars(
        select(Decision).where(Decision.is_current, Decision.status == "approved")
        .options(selectinload(Decision.reviews), selectinload(Decision.transaction))
    ).all()
    rows = []
    for d in decisions:
        obligation = next((o for o in d.obligations if o["type"] == report_type), None)
        if obligation is None:
            continue
        txn: Transaction = d.transaction
        acc = session.get(Account, txn.account_id)
        approvals = [r for r in d.reviews if r.action in ("approve", "modify")]
        rows.append({
            "report_type": report_type, "decision_id": d.id, "transaction_id": txn.id,
            "transaction_date": txn.timestamp.date().isoformat(),
            "account_masked": mask_account(acc.account_number if acc else ""),
            "amount_inr": f"{txn.amount_inr:.2f}", "channel": txn.channel, "direction": txn.direction,
            "counterparty_country": txn.counterparty_country,
            "rules": ";".join(h["rule_id"] for h in d.rules_fired), "deadline": obligation.get("deadline") or "",
            "approved_by": ";".join(sorted({a.reviewer for a in approvals})),
            "approved_at": approvals[-1].created_at.isoformat(timespec="seconds") if approvals else "",
        })
    return sorted(rows, key=lambda r: r["transaction_date"])


def to_csv(rows: list[dict[str, Any]]) -> str:
    buf = io.StringIO()
    buf.write("# DRAFT — generated by RegLens for review; not for submission to FIU-IND\n")
    writer = csv.DictWriter(buf, fieldnames=COLUMNS)
    writer.writeheader()
    writer.writerows(rows)
    return buf.getvalue()


def to_markdown(report_type: str, rows: list[dict[str, Any]]) -> str:
    title = REPORT_TYPES[report_type.upper()]
    lines = [f"# DRAFT {title} ({report_type.upper()})", "",
             "> **DRAFT** — generated from human-approved decisions only. Not for submission. "
             "Educational prototype; verify against FIU-IND formats.", ""]
    if not rows:
        lines.append("_No approved decisions carry this obligation yet._")
        return "\n".join(lines) + "\n"
    lines += ["| Txn | Date | Account | Amount | Channel | Rules | Deadline | Approved by |",
              "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['transaction_id']} | {r['transaction_date']} | {r['account_masked']} | "
                     f"{format_inr(float(r['amount_inr']))} | {r['channel']} | {r['rules']} | {r['deadline']} | "
                     f"{r['approved_by']} |")
    return "\n".join(lines) + "\n"
